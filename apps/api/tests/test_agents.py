def test_an_existing_agent_asset_is_adopted_not_duplicated(
    agents: AgentFactory, owner_identity: Identity, integration_engine: Engine
) -> None:
    """An inventory that already knows the agent gains an identity; it is not copied.

    This is the situation an organization is in when its inventory predates the
    registry: the asset exists. Registering it attaches the identity to that record,
    fills an owner slot that was empty, and changes nothing that was already decided.
    """
    asset_id = insert_agent_asset(
        integration_engine,
        organization_id=agents.organization_id,
        name="Legacy Agent",
        external_identifier="legacy-1",
        environment="staging",
    )
    adopted = agents.register(
        display_name="Legacy Agent",
        category=AgentCategory.DATA.value,
        version="0.9",
        environment="staging",
        owner_user_id=str(owner_identity.user_id),
        external_identifier="legacy-1",
    )
    assert adopted is not None
    assert adopted.asset_id == asset_id

    with bind_tenant(agents.organization_id), integration_engine.connect() as connection:
        asset_count = connection.execute(
            text(
                "SELECT count(*) FROM aicore.assets WHERE organization_id = :organization_id "
                "AND asset_type = 'agent' AND external_identifier = 'legacy-1'"
            ),
            {"organization_id": str(agents.organization_id)},
        ).scalar_one()
        owner = connection.execute(
            text(
                "SELECT owner_membership_id FROM aicore.assets WHERE id = :asset_id "
                "AND organization_id = :organization_id"
            ),
            {"asset_id": str(asset_id), "organization_id": str(agents.organization_id)},
        ).scalar_one()
    assert asset_count == 1
    assert owner == owner_identity.membership_id


def test_adoption_refuses_to_overwrite_what_is_recorded(
    agents: AgentFactory, identity_factory: IdentityFactory, integration_engine: Engine
) -> None:
    """A registration that contradicts the existing record is refused, not applied.

    Every claim a registration is *allowed* to make is tried against a record that
    says something else: the name, the environment, the lifecycle state and the
    owner. Each is a 409, and afterwards the record is byte-for-byte what it was —
    which is the property that makes adopting an existing asset safe.
    """
    insert_agent_asset(
        integration_engine,
        organization_id=agents.organization_id,
        name="Legacy Agent",
        external_identifier="legacy-2",
        environment="staging",
        status="active",
    )
    for contradiction in (
        {"display_name": "A Different Name"},
        {"environment": "production"},
        {"status": "draft"},
    ):
        refused = agents.register(
            category=AgentCategory.DATA.value,
            version="0.9",
            external_identifier="legacy-2",
            **contradiction,
            expected_status=409,
        )
        assert refused is None

    with bind_tenant(agents.organization_id), integration_engine.connect() as connection:
        row = connection.execute(
            text(
                "SELECT name, environment, status, owner_membership_id FROM aicore.assets "
                "WHERE organization_id = :organization_id AND external_identifier = 'legacy-2'"
            ),
            {"organization_id": str(agents.organization_id)},
        ).one()
    assert row.name == "Legacy Agent"
    assert row.environment == "staging"
    assert row.status == "active"
    assert row.owner_membership_id is None
    assert count_agent_rows(integration_engine, agents.organization_id) == 0


def test_adoption_fills_an_empty_owner_slot_without_choosing_an_owner_itself(
    agents: AgentFactory,
    owner_identity: Identity,
    identity_factory: IdentityFactory,
    integration_engine: Engine,
) -> None:
    """Filling a gap is allowed; replacing a decision is not.

    Two records, two answers. An unowned asset gains the owner the registration
    names, because nothing is being overwritten. An asset that already has an owner
    refuses a registration that names somebody else — a 409, not a reassignment —
    because ownership is a decision an operator made, and re-registering an agent is
    not a way to undo it.
    """
    other_member = identity_factory.join(
        identity_factory(role_code="viewer"),
        organization_id=agents.organization_id,
        role_code="viewer",
    )
    other_membership_id = next(
        membership_id
        for organization_id, membership_id in other_member.memberships()
        if organization_id == agents.organization_id
    )

    unowned_asset_id = insert_agent_asset(
        integration_engine,
        organization_id=agents.organization_id,
        name="Unowned Agent",
        external_identifier="legacy-3",
    )
    filled = agents.register(
        display_name="Unowned Agent",
        category=AgentCategory.DATA.value,
        version="0.9",
        external_identifier="legacy-3",
        owner_user_id=str(other_member.user_id),
    )
    assert filled is not None
    assert filled.asset_id == unowned_asset_id
    assert filled.body["owner"]["membership_id"] == str(other_membership_id)

    owned_asset_id = insert_agent_asset(
        integration_engine,
        organization_id=agents.organization_id,
        name="Owned Agent",
        external_identifier="legacy-4",
        owner_membership_id=other_membership_id,
    )
    refused = agents.register(
        display_name="Owned Agent",
        category=AgentCategory.DATA.value,
        version="0.9",
        external_identifier="legacy-4",
        # A different, entirely valid, active member of this organization: the
        # refusal is about what is already recorded, not about who is asking.
        owner_user_id=str(owner_identity.user_id),
        expected_status=409,
    )
    assert refused is None
    with bind_tenant(agents.organization_id), integration_engine.connect() as connection:
        owner = connection.execute(
            text(
                "SELECT owner_membership_id FROM aicore.assets WHERE id = :asset_id "
                "AND organization_id = :organization_id"
            ),
            {"asset_id": str(owned_asset_id), "organization_id": str(agents.organization_id)},
        ).scalar_one()
    assert owner == other_membership_id
    assert count_agent_rows(integration_engine, agents.organization_id) == 1


