"""Phase 4 at the database layer: identity, relationships, constraints, lifecycle.

These tests ask what the *schema* guarantees, not what a handler happens to do:

- an agent's identity is generated by the database, is unique per tenant, and does
  not change when the agent is renamed or its version changes;
- the registry and the inventory are linked one-to-one, and the link is enforced by
  PostgreSQL rather than by remembering to check it in Python;
- an identity cannot be attached to another tenant's asset, to a nonexistent asset,
  or to an asset twice — including when the attempt is raw SQL;
- a lifecycle move the transition table forbids is refused, and ``retired`` is
  terminal;
- the vocabularies (category, version, lifecycle) are closed in the database too;
- deleting the inventory record removes the identity with it, so an orphaned
  identity is not a state the database can reach.

The database-level assertions deliberately use a raw connection for setup: a case
the API is designed to refuse cannot be set up through the API.
"""

