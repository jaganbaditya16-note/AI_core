def test_only_draft_and_active_can_start_a_record() -> None:
    """Suspended and retired are states an agent moves *to*, not states it starts in."""
    assert {AssetStatus.DRAFT, AssetStatus.ACTIVE} == AGENT_INITIAL_STATES
    for allowed in AGENT_INITIAL_STATES:
        assert validate_initial_status(allowed.value) is allowed
    for refused in (AssetStatus.SUSPENDED, AssetStatus.RETIRED):
        with pytest.raises(ValueError, match=f"cannot start {refused.value}"):
            validate_initial_status(refused.value)


