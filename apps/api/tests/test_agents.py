def test_an_organization_with_agents_cannot_be_deleted_by_accident(
    agents: AgentFactory, integration_engine: Engine
) -> None:
    """The tenant boundary is RESTRICT: removing a tenant is an explicit procedure.

    The memberships are removed first so the refusal can only come from the
    registry: an organization whose agents still exist cannot be deleted, and the
    error names the registry's own foreign key.
    """
    agents.register()
    with (
        bind_tenant(agents.organization_id),
        integration_engine.begin() as connection,
    ):
        connection.execute(
            text("DELETE FROM aicore.memberships WHERE organization_id = :organization_id"),
            {"organization_id": str(agents.organization_id)},
        )
    with (
        pytest.raises(IntegrityError) as captured,
        bind_tenant(agents.organization_id),
        integration_engine.begin() as connection,
    ):
        connection.execute(
            text("DELETE FROM aicore.organizations WHERE id = :organization_id"),
            {"organization_id": str(agents.organization_id)},
        )
    # The asset is what PostgreSQL reports first — the registry row references the
    # asset, and the asset references the tenant. The registry holds its own
    # RESTRICT reference as well, asserted structurally below, so the boundary does
    # not depend on which of the two columns answers first.
    assert "fk_assets_organization_id_organizations" in str(captured.value.orig)
    with bind_tenant(agents.organization_id), integration_engine.connect() as connection:
        remaining = connection.execute(
            text("SELECT count(*) FROM aicore.agents WHERE organization_id = :organization_id"),
            {"organization_id": str(agents.organization_id)},
        ).scalar_one()
    assert remaining == 1


def test_the_registry_references_the_tenant_and_its_record_explicitly(
    integration_engine: Engine,
) -> None:
    """Both references, and what they do on delete, are readable from the catalog.

    ``(organization_id, asset_id) → assets`` cascades, because an identity whose
    agent is gone is an orphan. ``organization_id → organizations`` restricts, so a
    tenant cannot be removed out from under its registry by a cascade. The second is
    redundant while the first exists, and it is there on purpose: the tenant boundary
    of this table should not depend on another table's constraint.
    """
    with integration_engine.connect() as connection:
        constraints = dict(
            connection.execute(
                text(
                    "SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint "
                    "WHERE conrelid = to_regclass(CAST(:qualified AS text))"
                ),
                {"qualified": "aicore.agents"},
            ).all()
        )
    assert constraints["fk_agents_organization_id_assets"] == (
        "FOREIGN KEY (organization_id, asset_id) REFERENCES assets(organization_id, id) "
        "ON DELETE CASCADE"
    )
    assert constraints["fk_agents_organization_id_organizations"] == (
        "FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE RESTRICT"
    )


