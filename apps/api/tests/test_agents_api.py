"""Phase 4 over HTTP: registration, identity, lifecycle, authorization, isolation.

The registry's tests are written the way its callers use it — authenticated requests
against the real database — so every assertion here is about behaviour a client
actually gets:

- the response contract (exact fields, no credential ever appears);
- identity generated by the server, stable across renames and version changes, and
  impossible for a client to set;
- lifecycle moves recorded, impossible moves refused through the error envelope;
- authorization per operation, checked against the permission table for every role,
  and read structurally from the built application;
- tenant isolation: another organization's agent, identity, owner or tenant is never
  reachable, and never distinguishable from one that does not exist;
- the boundary of this phase: no endpoint executes, controls or contains an agent,
  and the agent permission namespace holds nothing that would claim to.

One fixture detail shapes the order of these tests: :func:`authenticate` attaches a
token to the *shared* test client, so a test that acts as somebody else switches
identity for the client it is holding. Scene-setting therefore happens first, as the
owner, and follow-up reads that must be the owner's switch the client back.
"""

