def test_the_lifecycle_moves_are_recorded_and_retirement_is_final(agents: AgentFactory) -> None:
    """The transition table, exercised through the API."""
    created = agents.register(status="active")
    assert created is not None
    url = _agent_url(created.organization_id, created.id)

    assert agents.client.patch(url, json={"status": "suspended"}).json()["status"] == "suspended"
    # A suspended agent is still a readable record: this is a registry state, not a
    # kill switch, and nothing in this build acts on it.
    assert agents.client.get(url).status_code == 200
    assert agents.client.patch(url, json={"status": "active"}).json()["status"] == "active"
    assert agents.client.patch(url, json={"status": "retired"}).json()["status"] == "retired"

    refused = agents.client.patch(url, json={"status": "active"})
    assert refused.status_code == 409
    assert refused.json()["error"]["code"] == "conflict"
    assert agents.client.get(url).json()["status"] == "retired"

    draft = agents.register(display_name="Draft Agent")
    assert draft is not None
    draft_url = _agent_url(draft.organization_id, draft.id)
    assert agents.client.patch(draft_url, json={"status": "suspended"}).status_code == 409
    assert agents.client.patch(draft_url, json={"status": "retired"}).status_code == 200


