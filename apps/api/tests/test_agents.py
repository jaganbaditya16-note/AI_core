# ── Lifecycle, through the API ───────────────────────────────────────────────


def test_lifecycle_moves_are_recorded_and_impossible_ones_refused(
    agents: AgentFactory,
) -> None:
    """``active → suspended → active → retired`` works; ``retired → active`` does not.

    Suspension is a record. Nothing is stopped, blocked or revoked by moving an agent
    to ``suspended`` — this build has no runtime to control, and the test asserts the
    move (a stored state) rather than an effect it cannot have.
    """
    created = agents.register(status="active")
    assert created is not None
    path = f"/organizations/{created.organization_id}/agents/{created.id}"

    def move(target: str) -> Any:
        return agents.client.patch(path, json={"status": target})

    assert move("suspended").json()["status"] == "suspended"
    assert move("active").json()["status"] == "active"
    assert move("retired").json()["status"] == "retired"

    refused = move("active")
    assert refused.status_code == 409
    assert "terminal" in refused.json()["error"]["message"]
    assert agents.client.get(path).json()["status"] == "retired"


