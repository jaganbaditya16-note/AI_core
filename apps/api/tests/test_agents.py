def test_identity_metadata_refuses_credentials_outright() -> None:
    """Runtime identity facts are allowed; anything shaped like a secret is not.

    The check runs over the raw keys *and* over the declared fields, so a key that
    merely looks like a credential never reaches the database — and the model's own
    ``extra="forbid"`` means an undeclared key is refused as well.
    """
    accepted = validate_identity_metadata(
        {"runtime": "python3.11", "region": "ap-south-1", "instance": "pod-7"}
    )
    assert accepted == {"runtime": "python3.11", "region": "ap-south-1", "instance": "pod-7"}
    assert validate_identity_metadata(None) is None
    assert validate_identity_metadata({}) is None

    for key in ("api_key", "API_KEY", "token", "secret", "password", "private_key", "credential"):
        with pytest.raises(ValueError, match="credentials"):
            validate_identity_metadata({key: "whatever"})
    with pytest.raises(ValueError):
        validate_identity_metadata({"runtime": "python3.11", "notes": "not a declared field"})
    with pytest.raises(ValueError):
        validate_identity_metadata({"runtime": "  "})
    # The declared fields are what bound a payload, and the model is the reason a
    # credential-shaped key cannot be smuggled in as "extra data": unknown keys are
    # refused before the serialized size is even considered. The byte budget in
    # ``validate_identity_metadata`` is a backstop for whatever a later phase adds
    # to this model — three 64-character labels cannot approach it today.
    assert max(len(name) for name in ("runtime", "region", "instance")) < 32
    assert IDENTITY_METADATA_MAX_BYTES >= 1024
    with pytest.raises(ValueError):
        validate_identity_metadata({"runtime": "x" * 65})


