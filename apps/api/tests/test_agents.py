    columns = {
        "id",
        "organization_id",
        "identity_id",
        "asset_id",
        "category",
        "version",
        "build_revision",
        "framework",
        "identity_metadata",
        "created_at",
        "updated_at",
    }
    with integration_engine.connect() as connection:
        actual = {
            row[0]
            for row in connection.execute(
                text(
                    "SELECT column_name FROM information_schema.columns "
                    "WHERE table_schema = 'aicore' AND table_name = :table_name"
                ),
                {"table_name": "agents"},
            )
        }
    assert actual == columns
    assert not {"name", "display_name", "status", "environment", "owner_membership_id"} & actual


