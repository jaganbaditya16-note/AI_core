def test_filters_narrow_the_page(agents: AgentFactory, owner_identity: Identity) -> None:
    """Category filters the registry; status, environment and owner filter the record."""
    agents.register(display_name="Assistant One", category="assistant", environment="production")
    agents.register(display_name="Coding One", category="coding", environment="staging")
    coding = agents.register(display_name="Coding Two", category="coding", environment="staging")
