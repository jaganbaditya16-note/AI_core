def test_version_labels_are_normalised_not_rejected() -> None:
    """A version is a label: real-world versions must survive, whitespace must not."""
    assert normalize_version("  1.2.0  ") == "1.2.0"
    assert normalize_version("2026-05-18") == "2026-05-18"
    assert normalize_version("0.1.0-rc1") == "0.1.0-rc1"
    assert normalize_version("release train B") == "release train B"
    for unusable in ("", "   ", "\t"):
        with pytest.raises(ValueError, match="version"):
            normalize_version(unusable)
    with pytest.raises(ValueError, match="version"):
        normalize_version("v" * (VERSION_MAX_LENGTH + 1))


