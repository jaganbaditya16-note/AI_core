def test_another_organization_cannot_determine_whether_an_agent_exists(
    agents: AgentFactory, identity_factory: IdentityFactory, authenticate
) -> None:
    """A foreign id and an invented id produce the same status *and* the same body.

    That is what makes the 404 a non-disclosure rather than a hint: the difference
    between "yours, but not yours to see" and "does not exist" is not observable.
    """
    created = agents.register()
    assert created is not None
    outsider = identity_factory(role_code="owner")
    client = authenticate(outsider)
    tenant = outsider.organization_id

    foreign = client.get(_agent_url(tenant, created.id))
    invented = client.get(_agent_url(tenant, uuid.uuid4()))
    assert foreign.status_code == invented.status_code == 404
    assert foreign.json()["error"]["message"] == invented.json()["error"]["message"]

    foreign_identity = client.get(identity_path(tenant, created.identity_id))
    invented_identity = client.get(identity_path(tenant, uuid.uuid4()))
    assert foreign_identity.status_code == invented_identity.status_code == 404
    assert (
        foreign_identity.json()["error"]["message"] == invented_identity.json()["error"]["message"]
    )


