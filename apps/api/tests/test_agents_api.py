#: Every field an agent response may contain. Asserted exactly, so a future field
#: (a credential, a runtime handle) cannot appear in the contract unnoticed.
AGENT_FIELDS = {
    "id",
    "organization_id",
    "identity_id",
    "asset_id",
    "display_name",
    "description",
    "category",
    "version",
    "framework",
    "build_revision",
    "status",
    "environment",
    "identity_metadata",
    "owner",
    "created_at",
    "updated_at",
}

#: The prefix every registry route shares.
_AGENT_PARENT = "/organizations/{organization_id}/agents"


def _agent_url(organization_id: uuid.UUID, agent_id: uuid.UUID | str) -> str:
    """The item URL for one registered agent."""
    return f"{agents_path(organization_id)}/{agent_id}"


