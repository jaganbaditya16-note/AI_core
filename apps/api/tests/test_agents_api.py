def test_no_role_holds_permissions_the_registry_did_not_introduce() -> None:
    """The agent namespace holds exactly the four registry permissions.

    Stated as an assertion because the temptation to widen a role while adding a
    feature is exactly how a least-privilege table erodes — and because a permission
    for executing, suspending or containing an agent now would be a claim this build
    cannot honour.
    """
    assert {permission for permission in Permission if permission.value.startswith("agent.")} == {
        Permission.AGENT_READ,
        Permission.AGENT_CREATE,
        Permission.AGENT_UPDATE,
        Permission.AGENT_DELETE,
    }
    assert set(ROLE_PERMISSIONS) == set(RoleCode)
    for role, permissions in ROLE_PERMISSIONS.items():
        assert permissions <= set(Permission), role
        # Every role that may change an agent may also read it: a permission to move
        # something you cannot see would be an incoherent grant.
        if Permission.AGENT_UPDATE in permissions or Permission.AGENT_DELETE in permissions:
            assert Permission.AGENT_READ in permissions


def _required_permissions(route: APIRoute) -> set[Permission]:
    """Permissions a route declares, read from its dependency tree."""
    found: set[Permission] = set()
    pending = list(route.dependant.dependencies)
    while pending:
        dependency = pending.pop()
        permission = getattr(dependency.call, "required_permission", None)
        if permission is not None:
            found.add(permission)
        pending.extend(dependency.dependencies)
    return found


def _agent_routes(app: FastAPI) -> dict[tuple[str, str], set[Permission]]:
    declared: dict[tuple[str, str], set[Permission]] = {}
    # `app.routes` yields lazily-included routers; iter_route_contexts is how
    # FastAPI itself walks the effective routes.
    for context in iter_route_contexts(app.routes):
        route = context.original_route
        if not isinstance(route, APIRoute):
            continue
        # The registry's own routes: the collection and its items. Matched on path
        # *segments* rather than on the string "/agents", because a later phase's view can
        # legitimately contain that segment — /monitoring/agents measures the same subject
        # without being a registry route, and this test is about the registry.
        if route.path != _AGENT_PARENT and not route.path.startswith(f"{_AGENT_PARENT}/"):
            continue
        for method in route.methods - {"HEAD", "OPTIONS"}:
            declared[(method, route.path)] = _required_permissions(route)
    return declared


def test_every_registry_route_declares_the_permission_it_enforces() -> None:
    """Authorization is a property of the route, not of the handler body.

    Read from the built application rather than from the source: a route that
    forgets its requirement — or acquires the wrong one in a refactor — fails here.
    """
    assert _agent_routes(create_app()) == {
        ("GET", _AGENT_PARENT): {Permission.AGENT_READ},
        ("POST", _AGENT_PARENT): {Permission.AGENT_CREATE},
        ("GET", f"{_AGENT_PARENT}/identity/{{identity_id}}"): {Permission.AGENT_READ},
        ("GET", f"{_AGENT_PARENT}/{{agent_id}}"): {Permission.AGENT_READ},
        ("PATCH", f"{_AGENT_PARENT}/{{agent_id}}"): {Permission.AGENT_UPDATE},
        ("DELETE", f"{_AGENT_PARENT}/{{agent_id}}"): {Permission.AGENT_DELETE},
    }


